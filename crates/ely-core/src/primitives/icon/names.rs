use std::fmt;

macro_rules! icons {
    ($($variant:ident => $file:literal,)*) => {
        /// One static per SVG, so a program links only the icons it names.
        #[allow(non_upper_case_globals)]
        mod svgs {
            $(pub(super) static $variant: &[u8] = include_bytes!(concat!("../../../icons/", $file, ".svg"));)*
        }

        #[allow(non_upper_case_globals)]
        impl IconName {
            $(#[doc = concat!("Lucide's `", $file, "`.")]
            pub const $variant: IconName = IconName { name: $file, svg: &svgs::$variant };)*

            /// Every bundled icon.
            pub const ALL: &[IconName] = &[$(IconName::$variant,)*];
        }
    };
}

/// A Lucide icon bundled with Ely: its name and its SVG.
#[derive(Clone, Copy)]
pub struct IconName {
    name: &'static str,
    svg: &'static &'static [u8],
}

impl IconName {
    /// Lucide name, such as `chevron-down`.
    pub fn name(self) -> &'static str {
        self.name
    }

    /// The SVG, as Lucide ships it.
    pub fn svg(self) -> &'static [u8] {
        self.svg
    }
}

impl PartialEq for IconName {
    fn eq(&self, other: &Self) -> bool {
        self.name == other.name
    }
}

impl Eq for IconName {}

impl std::hash::Hash for IconName {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.name.hash(state);
    }
}

impl fmt::Debug for IconName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name)
    }
}

